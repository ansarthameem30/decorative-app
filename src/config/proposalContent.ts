import { deserializeProposalConfig } from '../utils/proposalShare';

const STORAGE_KEY = "proposal_user_config_v3";

export const getStoredProposalConfig = (): ProposalConfig => {
  if (typeof window === "undefined") return defaultProposalConfig;
  
  // 1. Check if URL contains personalized proposal data (?p=...)
  try {
    const params = new URLSearchParams(window.location.search);
    const encodedData = params.get('p');
    if (encodedData) {
      const decoded = deserializeProposalConfig(encodedData);
      if (decoded) {
        const merged: ProposalConfig = {
          ...defaultProposalConfig,
          ...decoded,
          storySlides: decoded.storySlides && decoded.storySlides.length > 0 
            ? decoded.storySlides.map((slide, idx) => ({
                ...defaultProposalConfig.storySlides[idx],
                ...slide,
              }))
            : defaultProposalConfig.storySlides,
        };
        try {
          localStorage.setItem(STORAGE_KEY, JSON.stringify(merged));
        } catch (_) {}
        return merged;
      }
    }
  } catch (e) {
    console.warn("Could not read URL proposal config", e);
  }

  // 2. Check localStorage
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      return { ...defaultProposalConfig, ...JSON.parse(saved) };
    }
  } catch (e) {
    console.warn("Could not read stored proposal config", e);
  }
  return defaultProposalConfig;
};

export const saveStoredProposalConfig = (config: ProposalConfig) => {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
  } catch (e) {
    console.warn("Could not save proposal config", e);
  }
};
